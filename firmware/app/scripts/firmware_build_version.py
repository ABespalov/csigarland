# Purpose: Write the numbered firmware identity the build embeds.
# Contributors: None
#
# One identity reaches the image by two routes: esp_app_desc.version comes from
# CMake's PROJECT_VER and the display string from generated/firmware_version.h.
# deploy/flash-device.ps1 checks that both agree before anything is written.
#
# The counter moves only when CSIGARLAND_INCREMENT_BUILD=1, which the flash
# script sets. A plain `pio run` keeps the previous number. CSIGARLAND_BUILD_NUMBER
# names one outright, to build a release again as its manifest records it, and
# leaves the counter as it is.
#
# The compiler's __DATE__ and __TIME__ come from CSIGARLAND_SOURCE_DATE in
# platformio.ini, by SOURCE_DATE_EPOCH, rather than from the day of the build.
#
# CSIGARLAND_PROFILE picks the profile. "release" compiles with no debug information,
# which keeps the paths of the machine out of the ELF the image hashes, and gives the
# plain version, such as 1.0.0.102. "dev", the default for a plain `pio run`, keeps
# ESP-IDF's debug information and marks the version, as 1.0.0.102-dev, so that it is
# never taken for a release.

Import("env")

import calendar
import datetime
import hashlib
import os
import re
from pathlib import Path

_BASE_RE = re.compile(
    r"^CSIGARLAND_FIRMWARE_BASE\s*=\s*"
    r"(\d+)\.(\d+)\.(\d+)(?:-([0-9A-Za-z][0-9A-Za-z.-]*))?\s*$",
    re.MULTILINE,
)
_COUNTER_FILE = ".csigarland_build_counter"
_PROFILES = ("release", "dev")
_SOURCE_DATE_RE = re.compile(r"^CSIGARLAND_SOURCE_DATE\s*=\s*(\d{4}-\d{2}-\d{2})\s*$", re.MULTILINE)


# The firmware's own code reads the date from generated/source_date.h, as __DATE__ writes it, so a
# changed date compiles again what uses it. Anything else that asks for __DATE__ gets it too.
def _pin_source_date(ini_text: str, generated: Path) -> None:
    match = _SOURCE_DATE_RE.search(ini_text)
    if match is None:
        raise RuntimeError("CSIGARLAND_SOURCE_DATE not found in platformio.ini")
    day = datetime.date.fromisoformat(match.group(1))
    epoch = str(calendar.timegm(day.timetuple()))
    # For the compilers SCons runs, and for CMake and what it runs.
    env["ENV"]["SOURCE_DATE_EPOCH"] = epoch
    os.environ["SOURCE_DATE_EPOCH"] = epoch
    as_compiler_writes_it = f"{day:%b} {day.day:>2} {day.year}"
    _write_if_changed(
        generated / "source_date.h",
        "// Generated by firmware_build_version.py from CSIGARLAND_SOURCE_DATE. Do not edit.\n"
        "#pragma once\n"
        f'#define CSIGARLAND_SOURCE_DATE "{as_compiler_writes_it}"\n',
    )


def _read_counter(path: Path) -> int:
    if not path.is_file():
        return 0
    raw = path.read_text(encoding="utf-8").strip()
    if not raw.isdigit():
        raise RuntimeError(f"invalid firmware build counter: {path}")
    return int(raw)


def _write_if_changed(path: Path, text: str) -> None:
    if path.is_file() and path.read_text(encoding="utf-8") == text:
        return
    path.write_text(text, encoding="utf-8")


def _invalidate_stale_configure(build_dir: Path, project_ver: Path) -> None:
    # PlatformIO re-runs CMake only when build.ninja is missing or older than a
    # fixed list of inputs, and project_ver.cmake is not on it. Without this the
    # image would keep the previous esp_app_desc version under a new display
    # string.
    ninja = build_dir / "build.ninja"
    if ninja.is_file() and project_ver.stat().st_mtime_ns >= ninja.stat().st_mtime_ns:
        ninja.unlink()


def _renew_stale_sdkconfig(project_dir: Path, build_dir: Path) -> None:
    # ESP-IDF makes sdkconfig.<env> from sdkconfig.defaults once and keeps it after, so a changed
    # default would never reach a checkout that has built before, only a clean one. The defaults'
    # digest is kept beside the build, and when they change the effective config is made again.
    defaults = project_dir / "sdkconfig.defaults"
    effective = project_dir / f"sdkconfig.{env.subst('$PIOENV')}"
    stamp = project_dir / "generated" / "sdkconfig.defaults.sha256"
    digest = hashlib.sha256(defaults.read_bytes()).hexdigest()
    if effective.is_file() and (not stamp.is_file() or stamp.read_text(encoding="utf-8").strip() != digest):
        print(f"sdkconfig.defaults changed: {effective.name} is made again from it.")
        effective.unlink()
        ninja = build_dir / "build.ninja"
        if ninja.is_file():
            ninja.unlink()
    _write_if_changed(stamp, digest + "\n")


def inject_build_version() -> None:
    project_dir = Path(env["PROJECT_DIR"])
    ini_text = (project_dir / "platformio.ini").read_text(encoding="utf-8")
    match = _BASE_RE.search(ini_text)
    if match is None:
        raise RuntimeError("CSIGARLAND_FIRMWARE_BASE not found in platformio.ini")

    generated = project_dir / "generated"
    generated.mkdir(parents=True, exist_ok=True)
    _pin_source_date(ini_text, generated)
    counter = project_dir / _COUNTER_FILE
    named = os.environ.get("CSIGARLAND_BUILD_NUMBER", "")
    if named:
        if not named.isdigit():
            raise RuntimeError(f"CSIGARLAND_BUILD_NUMBER must be a whole number, not {named!r}")
        build_number = int(named)
    else:
        build_number = _read_counter(counter)
        if os.environ.get("CSIGARLAND_INCREMENT_BUILD") == "1":
            build_number += 1
            counter.write_text(f"{build_number}\n", encoding="utf-8")

    profile = os.environ.get("CSIGARLAND_PROFILE", "").strip().lower() or "dev"
    if profile not in _PROFILES:
        raise RuntimeError(f"CSIGARLAND_PROFILE must be release or dev, not {profile!r}")

    version = f"{match.group(1)}.{match.group(2)}.{match.group(3)}.{build_number}"
    if match.group(4):
        version += f"-{match.group(4)}"
    if profile == "dev":
        version += "-dev"

    # ESP-IDF always compiles with -ggdb. A later -g0 wins, for every component and the project.
    no_debug = 'idf_build_set_property(COMPILE_OPTIONS "-g0" APPEND)\n' if profile == "release" else ""
    project_ver = generated / "project_ver.cmake"
    _write_if_changed(
        project_ver,
        "# Generated by firmware_build_version.py. Do not edit.\n"
        f'set(PROJECT_VER "{version}")\n' + no_debug,
    )
    _write_if_changed(
        generated / "firmware_version.h",
        "// Generated by firmware_build_version.py. Do not edit.\n"
        "#pragma once\n"
        f'#define CSIGARLAND_VERSION "{version}"\n',
    )
    _invalidate_stale_configure(Path(env.subst("$BUILD_DIR")), project_ver)
    _renew_stale_sdkconfig(project_dir, Path(env.subst("$BUILD_DIR")))
    print(f"CSIGARLAND_VERSION: {version} ({profile})")


inject_build_version()
