# Purpose: Turn the status glyph pictures in assets/glyphs into src/glyphs.h.
# Contributors: None
#
# Not part of the build: run it by hand after changing a picture. It needs Pillow, which
# the build itself does not. With a path it also writes an enlarged preview there:
#
#   python scripts/make_glyphs.py [preview.png]
#
# Pictures are dark ink on a light or transparent background. Ink becomes coverage, so
# the screen can draw a glyph in any accent colour.

import sys
from pathlib import Path

from PIL import Image

SIZE = 20
# Thin strokes lose contrast when scaled this far down; this brings them back.
INK_GAMMA = 0.72
GLYPHS = [("kBrightnessGlyph", "brightness"), ("kSpeedGlyph", "speed"), ("kLedsGlyph", "leds")]
# csiPass's header clock: its shape in 10 x 10 units, sampled four times a pixel each way.
CLOCK_SIZE = 15
CLOCK_UNITS = 10
CLOCK_SAMPLES = 4
PREVIEW_SCALE = 8
PREVIEW_BACKGROUND = (0x0F, 0x17, 0x2A)
PREVIEW_INK = (0x3B, 0x82, 0xF6)

ROOT = Path(__file__).resolve().parent.parent


def coverage(path: Path) -> Image.Image:
    picture = Image.open(path).convert("RGBA")
    white = Image.new("RGBA", picture.size, (255, 255, 255, 255))
    ink = Image.alpha_composite(white, picture).convert("L").point(lambda level: 255 - level)
    box = ink.point(lambda level: 255 if level > 64 else 0).getbbox()
    if box is None:
        raise SystemExit(f"{path}: no ink")
    ink = ink.crop(box)
    side = max(ink.size)
    square = Image.new("L", (side, side), 0)
    square.paste(ink, ((side - ink.width) // 2, (side - ink.height) // 2))
    small = square.resize((SIZE, SIZE), Image.Resampling.LANCZOS)
    return small.point(lambda level: round(255 * (level / 255) ** INK_GAMMA))


def clock_covers(u: float, v: float) -> bool:
    squared = (u - 5) ** 2 + (v - 5) ** 2
    if 3.9**2 <= squared <= 5**2:
        return True
    if 4.45 <= u <= 5.55 and 2.1 <= v <= 5.55:
        return True
    return 4.45 <= v <= 5.55 and 4.45 <= u <= 7.5


def clock_coverage() -> Image.Image:
    values = bytearray()
    to_units = CLOCK_UNITS / CLOCK_SIZE
    for row in range(CLOCK_SIZE):
        for column in range(CLOCK_SIZE):
            hits = sum(
                clock_covers((column + (x + 0.5) / CLOCK_SAMPLES) * to_units, (row + (y + 0.5) / CLOCK_SAMPLES) * to_units)
                for y in range(CLOCK_SAMPLES)
                for x in range(CLOCK_SAMPLES)
            )
            values.append(min(255, hits * 16))
    return Image.frombytes("L", (CLOCK_SIZE, CLOCK_SIZE), bytes(values))


def table(name: str, image: Image.Image, size: int, size_name: str) -> list[str]:
    values = image.tobytes()
    lines = [f"inline constexpr uint8_t {name}[{size_name} * {size_name}] = {{"]
    for i in range(0, len(values), size):
        lines.append("    " + ", ".join(f"{value:3d}" for value in values[i : i + size]) + ",")
    lines.append("};")
    return lines


def main() -> None:
    images = {name: coverage(ROOT / "assets" / "glyphs" / f"{source}.png") for name, source in GLYPHS}
    clock = clock_coverage()
    lines = [
        "/**",
        " * Copyright (c) 2026 Anton Bespalov. All rights reserved.",
        " * Licensed under the terms specified by the MIT License",
        " * Part of the csiGarland project https://github.com/ABespalov/csigarland",
        " *",
        " * Purpose: The screen's glyphs, as coverage it draws in the colour it chooses",
        " * Contributors: None",
        " *",
        " * Generated by scripts/make_glyphs.py from assets/glyphs and csiPass's clock. Do not edit.",
        " */",
        "",
        "#pragma once",
        "",
        "#include <cstdint>",
        "",
        "namespace garland {",
        "",
        f"constexpr int kGlyphSize = {SIZE};",
        f"constexpr int kClockGlyphSize = {CLOCK_SIZE};",
        "",
    ]
    for name, image in images.items():
        lines += table(name, image, SIZE, "kGlyphSize") + [""]
    lines += table("kClockGlyph", clock, CLOCK_SIZE, "kClockGlyphSize") + [""]
    lines += ["}  // namespace garland", ""]
    (ROOT / "src" / "glyphs.h").write_text("\n".join(lines), encoding="utf-8", newline="\n")

    if len(sys.argv) > 1:
        cell = (SIZE + 4) * PREVIEW_SCALE
        shown = [*images.values(), clock]
        sheet = Image.new("RGB", (cell * len(shown), cell), PREVIEW_BACKGROUND)
        for index, image in enumerate(shown):
            large = image.resize((image.width * PREVIEW_SCALE, image.height * PREVIEW_SCALE), Image.Resampling.NEAREST)
            sheet.paste(Image.new("RGB", large.size, PREVIEW_INK), (cell * index + 2 * PREVIEW_SCALE, 2 * PREVIEW_SCALE), large)
        sheet.save(sys.argv[1])


main()
